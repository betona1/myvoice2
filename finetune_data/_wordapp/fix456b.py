n=miss=0
for ch,ko in FIX.items():
    r=con.execute("SELECT id,meaning_ko,senses_ko FROM words WHERE chinese=? AND hsk BETWEEN 4 AND 6",(ch,)).fetchall()
    if not r: miss+=1; continue
    for wid,oko,sen in r:
        if (oko or '').strip()==ko: continue
        parts=[x.strip() for x in re.split(r'[①②③④⑤⑥⑦⑧]\s*',sen or '') if x.strip()]
        parts=[ko]+[x for x in parts if x!=ko and x!=(oko or '').strip()]
        ns=' '.join(f'{CIR[j]} {x}' for j,x in enumerate(parts[:6])) if len(parts)>1 else ko
        con.execute("UPDATE words SET meaning_ko=?,senses_ko=? WHERE id=?",(ko,ns,wid)); n+=1
