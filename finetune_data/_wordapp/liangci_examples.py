con = sqlite3.connect('database/voices.db', timeout=60); con.row_factory = sqlite3.Row
con.execute("""CREATE TABLE IF NOT EXISTS word_examples (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    word_id INTEGER NOT NULL,
    seq INTEGER,
    chinese TEXT NOT NULL,
    pinyin TEXT,
    meaning_ko TEXT,
    audio1 TEXT, audio2 TEXT,
    UNIQUE(word_id, chinese))""")
con.execute("CREATE INDEX IF NOT EXISTS idx_wex_word ON word_examples(word_id, seq)")

added = skipped = 0
for ch, items in EX.items():
    r = con.execute("SELECT id FROM words WHERE chinese=? AND COALESCE(excluded,0)=0", (ch,)).fetchone()
    if not r:
        print(f"  {ch}: DB에 없음"); continue
    for k, it in enumerate(items):
        zh, ko = it.split('|', 1)
        py = ' '.join(x[0] for x in _py(zh, style=Style.TONE))
        try:
            con.execute("""INSERT INTO word_examples(word_id,seq,chinese,pinyin,meaning_ko)
                           VALUES(?,?,?,?,?)""", (r['id'], k, zh, py, ko))
            added += 1
        except sqlite3.IntegrityError:
            skipped += 1
con.commit()
n = con.execute("""SELECT COUNT(*) FROM word_examples e JOIN words w ON w.id=e.word_id
                   WHERE w.wordset='양사'""").fetchone()[0]
have = con.execute("""SELECT COUNT(DISTINCT word_id) FROM word_examples e JOIN words w ON w.id=e.word_id
                      WHERE w.wordset='양사'""").fetchone()[0]
tot = con.execute("SELECT COUNT(*) FROM words WHERE wordset='양사' AND COALESCE(excluded,0)=0").fetchone()[0]
print(f"예문 {added}개 넣음 (이미 있던 것 {skipped}개)")
print(f"양사 {tot}개 중 예문 있는 것 {have}개 · 예문 총 {n}개")
miss = [r['chinese'] for r in con.execute("""SELECT chinese FROM words w WHERE w.wordset='양사'
        AND COALESCE(w.excluded,0)=0
        AND NOT EXISTS(SELECT 1 FROM word_examples e WHERE e.word_id=w.id)""")]
if miss:
    print("예문 없는 양사:", ' '.join(miss))
con.close()
