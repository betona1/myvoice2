con = sqlite3.connect('database/voices.db', timeout=60); con.execute('PRAGMA busy_timeout=60000')
from pypinyin import pinyin as _py, Style
hit = miss = 0
for ch, py, ko, sen in T:
    rows = con.execute("SELECT id,pinyin,meaning_ko FROM words WHERE chinese=? AND COALESCE(excluded,0)=0",(ch,)).fetchall()
    if not rows: print(f"   (없음) {ch}"); miss += 1; continue
    for wid, opy, oko in rows:
        if APPLY:
            if (opy or '').strip() != py:
                con.execute("UPDATE words SET pinyin=?,tones=? WHERE id=?",
                            (py, ' '.join(x[0] for x in _py(ch, style=Style.TONE3)), wid))
            con.execute("UPDATE words SET meaning_ko=?, senses_ko=? WHERE id=?", (ko, sen, wid))
        hit += 1
        if hit <= 6: print(f"   {ch} '{str(oko)[:22]}' → '{ko}'")
if APPLY: con.commit()
print(f"\n다음자 {len(T)}종 / 반영 {hit}건 / 없음 {miss}건" + ("" if APPLY else "  ※드라이런"))
con.close()
