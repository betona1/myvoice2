con=sqlite3.connect(DB,timeout=60); con.execute('PRAGMA busy_timeout=60000')
n=py_n=0
for ch, ko in FIX.items():
    r=con.execute("SELECT id,pinyin,meaning_ko,senses_ko FROM words WHERE chinese=?", (ch,)).fetchone()
    if not r: continue
    parts=[p.strip() for p in re.split(r'[①②③④⑤⑥⑦⑧]\s*', r[3] or '') if p.strip()]
    if ko in parts: parts.remove(ko)
    parts=[ko]+parts
    sen=' '.join(f'{CIR[j]} {p}' for j,p in enumerate(parts[:6])) if len(parts)>1 else ko
    # 병음: 고유명사로 오인돼 대문자면 상용 독음으로 교체
    py=r[1] or ''
    want=' '.join(p[0] for p in _py(ch, style=Style.TONE))
    newpy=py
    if py[:1].isupper() or py.strip().lower()!=want.strip().lower():
        newpy=want; py_n+=1
    tones=' '.join(p[0] for p in _py(ch, style=Style.TONE3))
    if r[2]!=ko: n+=1
    con.execute("UPDATE words SET meaning_ko=?, senses_ko=?, pinyin=?, tones=? WHERE id=?",
                (ko, sen, newpy, tones, r[0]))
con.commit()
print(f"  검수표 {len(FIX)}개 — 뜻 교정 {n}개 / 병음 교정 {py_n}개")
for w in ['分','块','本','回','岁','点','请','里','着','越','被','条']:
    r=con.execute("SELECT chinese,pinyin,meaning_ko FROM words WHERE chinese=?", (w,)).fetchone()
    if r: print(f"   {r[0]}  {r[1]:8s} {r[2]}")
con.close()
