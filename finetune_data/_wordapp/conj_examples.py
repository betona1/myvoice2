con = sqlite3.connect('database/voices.db', timeout=60); con.row_factory = sqlite3.Row
added = skip = 0
for table in (CONJ, SOUND):
    for ch, items in table.items():
        r = con.execute("SELECT id FROM words WHERE chinese=? AND COALESCE(excluded,0)=0",
                        (ch,)).fetchone()
        if not r:
            print(f"  {ch}: DB에 없음"); continue
        for k, it in enumerate(items):
            zh, ko = it.split('|', 1)
            py = ' '.join(x[0] for x in _py(zh, style=Style.TONE))
            try:
                con.execute("""INSERT INTO word_examples(word_id,seq,chinese,pinyin,meaning_ko)
                               VALUES(?,?,?,?,?)""", (r['id'], k, zh, py, ko))
                added += 1
            except sqlite3.IntegrityError:
                skip += 1
con.commit()
for t in ('접속사', '의성의태'):
    tot = con.execute("SELECT COUNT(*) FROM words WHERE wordset=? AND COALESCE(excluded,0)=0",
                      (t,)).fetchone()[0]
    have = con.execute("""SELECT COUNT(DISTINCT e.word_id) FROM word_examples e
                          JOIN words w ON w.id=e.word_id WHERE w.wordset=?""", (t,)).fetchone()[0]
    n = con.execute("""SELECT COUNT(*) FROM word_examples e JOIN words w ON w.id=e.word_id
                       WHERE w.wordset=?""", (t,)).fetchone()[0]
    miss = [x['chinese'] for x in con.execute("""SELECT chinese FROM words w WHERE w.wordset=?
            AND COALESCE(w.excluded,0)=0
            AND NOT EXISTS(SELECT 1 FROM word_examples e WHERE e.word_id=w.id)""", (t,))]
    print(f"{t}: {tot}개 중 예문 있는 것 {have}개 · 예문 {n}개" + (f" · 없는 것 {miss}" if miss else ""))
print(f"\n새로 넣은 예문 {added}개 (이미 있던 것 {skip}개)")
con.close()
