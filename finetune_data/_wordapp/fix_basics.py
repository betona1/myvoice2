# -*- coding: utf-8 -*-
"""HSK 기초 어휘 대표 뜻 확정.
숫자·대명사·기본 동사는 번역기에 맡기면 '九→나인', '八→8', '零→제로'처럼 어긋난다.
초급은 오답이 치명적이므로 규칙 + 검수표로 못박는다. 전체 뜻(senses_ko)은 유지."""
import os, re, sqlite3, sys
os.chdir('/app')
DB='database/voices.db'
CIR='①②③④⑤⑥⑦⑧'

FIX = {
 # 숫자
 '零':'영, 0','〇':'영, 0','一':'하나, 1','二':'둘, 2','两':'둘, 두 (양사 앞)','三':'셋, 3','四':'넷, 4',
 '五':'다섯, 5','六':'여섯, 6','七':'일곱, 7','八':'여덟, 8','九':'아홉, 9','十':'열, 10',
 '百':'백, 100','千':'천, 1000','万':'만, 10000','亿':'억',
 # 대명사·지시
 '我':'나, 저','你':'너, 당신','您':'당신 (높임말)','他':'그 (남자)','她':'그녀','它':'그것',
 '我们':'우리','你们':'너희, 여러분','他们':'그들','这':'이, 이것','那':'그, 저, 그것',
 '哪':'어느, 어디','谁':'누구','什么':'무엇, 무슨','哪儿':'어디','这儿':'여기','那儿':'거기, 저기',
 '几':'몇','多少':'얼마, 몇','怎么':'어떻게, 왜','为什么':'왜',
 # 기본 명사
 '字':'글자, 문자','人':'사람','年':'해, 년','月':'달, 월','日':'날, 일','天':'하늘, 날',
 '书':'책','水':'물','火':'불','山':'산','车':'차, 자동차','家':'집, 가정','名字':'이름',
 '东西':'물건','地':'땅, 지면','钱':'돈','手':'손','头':'머리','口':'입','眼睛':'눈',
 # 기본 형용사·동사
 '好':'좋다','大':'크다','小':'작다','多':'많다','少':'적다','高':'높다, (키가) 크다',
 '长':'길다 / (zhǎng) 자라다, 우두머리','热':'덥다, 뜨겁다','冷':'춥다, 차갑다',
 '新':'새롭다','旧':'낡다','快':'빠르다','慢':'느리다','远':'멀다','近':'가깝다',
 '读':'읽다','听':'듣다','说':'말하다','看':'보다','写':'쓰다','吃':'먹다','喝':'마시다',
 '去':'가다','来':'오다','走':'걷다, 가다','坐':'앉다, (교통수단을) 타다','买':'사다','卖':'팔다',
 '有':'있다, 가지다','是':'~이다','在':'~에 있다','做':'하다, 만들다','要':'원하다, ~하려 하다',
 # 부사·조사
 '不':'아니다 (부정)','没':'없다, ~하지 않았다','都':'모두, 다','也':'~도, 또한','很':'매우, 아주',
 '太':'너무','最':'가장','还':'아직, 또한','就':'곧, 바로','才':'비로소, 겨우',
 '行':'좋다, 괜찮다 / (háng) 줄, 업종','会':'~할 줄 알다, ~할 것이다','能':'~할 수 있다',
 '和':'~와, 그리고','的':'~의 (관형어 표지)','了':'~했다 (완료)','吗':'~입니까? (의문)',
 '呢':'~는요? (의문·지속)','吧':'~하자, ~겠지 (제안·추측)','喂':'여보세요 (전화)',
}

con=sqlite3.connect(DB,timeout=60); con.execute('PRAGMA busy_timeout=60000')
n=0; miss=[]
for ch, ko in FIX.items():
    r=con.execute("SELECT id,meaning_ko,senses_ko FROM words WHERE chinese=?", (ch,)).fetchone()
    if not r: miss.append(ch); continue
    parts=[p.strip() for p in re.split(r'[①②③④⑤⑥⑦⑧]\s*', r[2] or '') if p.strip()]
    if ko in parts: parts.remove(ko)
    parts=[ko]+parts
    sen=' '.join(f'{CIR[j]} {p}' for j,p in enumerate(parts[:6])) if len(parts)>1 else ko
    if r[1]!=ko:
        print(f"   {ch:6s} '{str(r[1])[:18]}' → '{ko}'")
        n+=1
    con.execute("UPDATE words SET meaning_ko=?, senses_ko=? WHERE id=?", (ko, sen, r[0]))
con.commit()
print(f"  검수표 {len(FIX)}개 중 {n}개 교정 / DB에 없음 {len(miss)}개")
if miss: print("   없음:", ' '.join(miss[:20]))
con.close()
