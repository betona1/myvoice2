def put(form, tag, ko, ex, exko, subject):
    r = con.execute("SELECT id FROM words WHERE chinese=?", (form,)).fetchone()
    se = f"① {ko} — {ex} {exko}"
    if r:
        con.execute("""UPDATE words SET meaning_ko=?, senses_ko=?, wordset=?, excluded=0,
                                        category='구문' WHERE id=?""", (ko, se, tag, r['id']))
        return 0
    seq = con.execute("SELECT COALESCE(MAX(seq),0)+1 FROM words").fetchone()[0]
    base = form.replace('…', '').replace('，', '').replace('（', '').replace('）', '')
    pin = ' '.join(x[0] for x in _py(base, style=Style.TONE)) if base else ''
    ton = ' '.join(x[0] for x in _py(base, style=Style.TONE3)) if base else ''
    con.execute("""INSERT INTO words(chinese,pinyin,tones,meaning_ko,senses_ko,hsk,
                                     category,subject,seq,level,difficulty,excluded,wordset)
                   VALUES(?,?,?,?,?,0,'구문',?,?,3,30,0,?)""",
                (form, pin, ton, ko, se, subject, seq, tag))
    return 1

