"""홀로는 뜻이 없고 짝을 이뤄야 말이 되는 글자들.
   사전 뜻이 'coffee' 하나뿐이라 옮기면 啡 이 '커피'가 되어 헷갈린다.
   어느 낱말의 글자인지 알려 주는 편이 배우는 데 낫다."""
import os, sqlite3
os.chdir('/app')
BOUND = {
 '啡':'「咖啡(커피)」의 글자', '咖':'「咖啡(커피)」의 글자',
 '玫':'「玫瑰(장미)」의 글자', '瑰':'「玫瑰(장미)」의 글자',
 '葡':'「葡萄(포도)」의 글자', '萄':'「葡萄(포도)」의 글자',
 '蕉':'「香蕉(바나나)」의 글자', '鸳':'「鸳鸯(원앙)」의 글자',
 '鸯':'「鸳鸯(원앙)」의 글자', '乒':'「乒乓(탁구)」의 글자',
 '乓':'「乒乓(탁구)」의 글자', '篷':'「帐篷(천막)」의 글자',
 '墅':'「别墅(별장)」의 글자', '厦':'「大厦(빌딩)」의 글자',
 '匙':'「钥匙(열쇠)」의 글자', '瑰':'「玫瑰(장미)」의 글자',
 '哗':'와르르 (물소리)', '咕':'꼬르륵 (소리)', '咚':'쿵 (소리)',
 '喵':'야옹 (고양이 소리)', '吞':'삼키다', '叮':'물다, 쏘다',
 '么':'「什么(무엇)」처럼 짝을 이루는 글자',
 '乎':'「几乎(거의)」처럼 짝을 이루는 글자',
 '晶':'「水晶(수정)」·「晶体(결정)」의 글자',
 '汪':'「汪汪(멍멍)」 개 짖는 소리',
 '钝':'무디다', '钥':'열쇠', '绵':'솜, 이어지다', '绳':'줄, 끈',
 '袜':'양말', '荐':'「推荐(추천)」의 글자', '绍':'「介绍(소개)」의 글자',
}
con=sqlite3.connect('database/voices.db', timeout=60)
n=0
for ch,ko in BOUND.items():
    # 손으로 적은 쪽이 사전보다 낫다 (葡 이 '포르투갈'로, 鸳 이 '만다린 오리'로 나왔다)
    con.execute("INSERT INTO char_ko(char,ko) VALUES(?,?) "
                "ON CONFLICT(char) DO UPDATE SET ko=excluded.ko", (ch,ko)); n+=1
con.commit()
print(f"손으로 채운 것 {n}자")
empty=[r[0] for r in con.execute("SELECT char FROM char_ko WHERE COALESCE(ko,'')=''")]
print("아직 빈 글자:", ''.join(empty) or '없음')
for ch in '啡玫葡蕉鸳乒':
    r=con.execute("SELECT ko FROM char_ko WHERE char=?", (ch,)).fetchone()
    print(f"  {ch} — {r[0] if r else '없음'}")
